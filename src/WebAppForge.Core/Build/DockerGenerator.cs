using System.Text;
using WebAppForge.Core.Generation;
using WebAppForge.Core.Model;

namespace WebAppForge.Core.Build;

/// <summary>
/// Writes the Docker artifacts for a generated site: Dockerfile and .dockerignore, and docker-compose.yml when
/// <see cref="BuildSettings.GenerateCompose"/> is set. The generated site reads <c>ConnectionStrings:Default</c> from
/// configuration, so the environment variable <c>ConnectionStrings__Default</c> overrides the database location. For a server
/// database (SQL Server, Azure SQL, MySQL) nothing about the connection is built into the image: it is passed in at run time.
/// </summary>
public sealed class DockerGenerator
{
    /// <summary>Folder inside the container that holds the SQLite file (a volume in compose).</summary>
    public const string DataFolder = "/data";

    /// <summary>Writes the files under <paramref name="outputDirectory"/> and returns their relative paths.</summary>
    public IReadOnlyList<string> Generate(Project project, string outputDirectory)
    {
        ArgumentNullException.ThrowIfNull(project);
        ArgumentException.ThrowIfNullOrEmpty(outputDirectory);

        var files = new Dictionary<string, string>
        {
            ["Dockerfile"] = Dockerfile(project),
            [".dockerignore"] = DockerIgnore(),
        };

        if (project.Build.GenerateCompose)
        {
            files["docker-compose.yml"] = Compose(project);
        }

        Directory.CreateDirectory(outputDirectory);
        var written = new List<string>();
        foreach (var (name, content) in files)
        {
            File.WriteAllText(Path.Combine(outputDirectory, name), content, new UTF8Encoding(false));
            written.Add(name);
        }

        return written;
    }

    public static string ContainerConnectionString(Project project)
    {
        var file = Path.GetFileName(project.Database.Path.Replace('\\', '/'));
        if (string.IsNullOrEmpty(file))
        {
            file = BuildSettings.SafeName(project.Name) + ".db";
        }

        return $"Data Source={DataFolder}/{file}";
    }

    public static string Dockerfile(Project project)
    {
        var build = project.Build;
        var csproj = Identifier.Pascal(project.Name) + ".csproj";
        var port = build.DockerExposePort;
        var sb = new StringBuilder();
        sb.Append("# Generated by WebAppForge. Build with: docker build -t ").Append(build.EffectiveImageName(project.Name)).Append(" .\n");
        sb.Append("FROM ").Append(build.DockerBaseSdkImage).Append(" AS build\n");
        sb.Append("WORKDIR /src\n");
        sb.Append("COPY \"").Append(csproj).Append("\" ./\n");
        sb.Append("RUN dotnet restore \"").Append(csproj).Append("\"\n");
        sb.Append("COPY . .\n");
        sb.Append("RUN dotnet publish \"").Append(csproj).Append("\" -c Release -o /app/publish --no-restore\n");
        sb.Append('\n');
        sb.Append("FROM ").Append(build.DockerBaseRuntimeImage).Append(" AS final\n");
        sb.Append("WORKDIR /app\n");
        sb.Append("# The official ASP.NET images run as the non-root user with this id.\n");
        sb.Append("ARG APP_UID=1654\n");
        var server = project.Database.IsServer;
        if (!server)
        {
            sb.Append("RUN mkdir -p ").Append(DataFolder).Append(" && chown ${APP_UID} ").Append(DataFolder).Append('\n');
        }

        sb.Append("COPY --from=build /app/publish .\n");
        sb.Append("USER ${APP_UID}\n");
        sb.Append("ENV ASPNETCORE_URLS=http://+:").Append(port).Append('\n');
        if (Templates.EnvironmentName(project.Meta) is { } environment)
        {
            sb.Append("ENV ASPNETCORE_ENVIRONMENT=").Append(environment).Append('\n');
        }

        if (server)
        {
            sb.Append("# The connection string is not part of the image. Pass it when the container starts, for example:\n");
            sb.Append("#   docker run -e ").Append(ServerVariable(project)).Append("=\"...\" ").Append(build.EffectiveImageName(project.Name)).Append('\n');
        }
        else
        {
            sb.Append("ENV ConnectionStrings__Default=\"").Append(ContainerConnectionString(project)).Append("\"\n");
            sb.Append("VOLUME ").Append(DataFolder).Append('\n');
        }

        sb.Append("EXPOSE ").Append(port).Append('\n');
        // The assembly name is the project name unless the project metadata sets one (see Templates.Csproj).
        var assembly = string.IsNullOrWhiteSpace(project.Meta.AssemblyName) ? Identifier.Pascal(project.Name) : project.Meta.AssemblyName.Trim();
        sb.Append("ENTRYPOINT [\"dotnet\", \"").Append(assembly).Append(".dll\"]\n");
        return sb.ToString();
    }

    /// <summary>The environment variable a server site reads its connection string from: the project's variable, else ConnectionStrings__Default.</summary>
    public static string ServerVariable(Project project) =>
        project.Database.ConnectionStringVariable.Trim() is { Length: > 0 } variable ? variable : "ConnectionStrings__Default";

    public static string DockerIgnore()
    {
        return string.Join('\n',
            "**/bin/",
            "**/obj/",
            "publish/",
            ".git/",
            ".vs/",
            "*.db",
            "*.db-shm",
            "*.db-wal",
            "Dockerfile",
            ".dockerignore",
            "docker-compose.yml",
            string.Empty);
    }

    public static string Compose(Project project)
    {
        var build = project.Build;
        var service = BuildSettings.SafeName(project.Name);
        var volume = service + "-data";
        var sb = new StringBuilder();
        sb.Append("# Generated by WebAppForge. Start with: docker compose up --build\n");
        var server = project.Database.IsServer;
        if (server)
        {
            var variable = ServerVariable(project);
            sb.Append("# The connection string comes from ").Append(variable).Append(" in the environment that runs docker compose.\n");
        }
        else
        {
            sb.Append("# The SQLite database lives in the named volume below, mounted at ").Append(DataFolder).Append(".\n");
        }

        sb.Append("services:\n");
        sb.Append("  ").Append(service).Append(":\n");
        sb.Append("    image: ").Append(build.EffectiveImageName(project.Name)).Append('\n');
        sb.Append("    build: .\n");
        sb.Append("    ports:\n");
        sb.Append("      - \"").Append(build.DockerExposePort).Append(':').Append(build.DockerExposePort).Append("\"\n");
        sb.Append("    environment:\n");
        sb.Append("      ASPNETCORE_URLS: \"http://+:").Append(build.DockerExposePort).Append("\"\n");
        if (server)
        {
            var variable = ServerVariable(project);
            sb.Append("      ").Append(variable).Append(": \"${").Append(variable).Append("}\"\n");
            sb.Append("    restart: unless-stopped\n");
            return sb.ToString();
        }

        sb.Append("      ConnectionStrings__Default: \"").Append(ContainerConnectionString(project)).Append("\"\n");
        sb.Append("    volumes:\n");
        sb.Append("      - ").Append(volume).Append(':').Append(DataFolder).Append('\n');
        sb.Append("    restart: unless-stopped\n");
        sb.Append('\n');
        sb.Append("volumes:\n");
        sb.Append("  ").Append(volume).Append(":\n");
        return sb.ToString();
    }
}
